import assert from 'node:assert/strict'
import { mkdtempSync, readFileSync, rmdirSync, unlinkSync, writeFileSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import test from 'node:test'
import { restoreGeneratedFileIfUnchanged } from './dev058-local-sso-app.mjs'

function withTempFile(run) {
  const directory = mkdtempSync(path.join(tmpdir(), 'dev058-local-sso-config-'))
  const filePath = path.join(directory, 'generated-config')
  try {
    return run(filePath)
  } finally {
    try { unlinkSync(filePath) } catch (error) { if (error?.code !== 'ENOENT') throw error }
    rmdirSync(directory)
  }
}

test('restores original bytes when generated bytes are unchanged', () => withTempFile((filePath) => {
  const before = Buffer.from('original\n')
  const generated = Buffer.from('generated\n')
  writeFileSync(filePath, generated)

  assert.equal(restoreGeneratedFileIfUnchanged(filePath, before, generated), true)
  assert.deepEqual(readFileSync(filePath), before)
}))

test('does not overwrite a later external modification', () => withTempFile((filePath) => {
  const before = Buffer.from('original\n')
  const generated = Buffer.from('generated\n')
  const external = Buffer.from('external change\n')
  writeFileSync(filePath, generated)
  writeFileSync(filePath, external)

  assert.equal(restoreGeneratedFileIfUnchanged(filePath, before, generated), false)
  assert.deepEqual(readFileSync(filePath), external)
}))

test('does not recreate a file deleted before cleanup', () => withTempFile((filePath) => {
  const before = Buffer.from('original\n')
  const generated = Buffer.from('generated\n')
  writeFileSync(filePath, generated)
  unlinkSync(filePath)

  assert.equal(restoreGeneratedFileIfUnchanged(filePath, before, generated), false)
  assert.equal(existsSync(filePath), false)
}))
